fn add_top_accent(mut g: [u8; 16], row0: u8, row1: u8) -> [u8; 16] {
    g[0] = row0;
    g[1] = row1;
    g
}

fn add_mid_bar(mut g: [u8; 16], row: usize, mask: u8) -> [u8; 16] {
    g[row] |= mask;
    g
}

