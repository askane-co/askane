#[inline]
pub fn bitmap_scaled_dims(size_px: i32) -> (i32, i32) {
    let h = size_px.clamp(8, 128);
    let w = ((BITMAP_CELL_W * h + BITMAP_CELL_H / 2) / BITMAP_CELL_H).max(4);
    (w, h)
}

/// Rasterizes one built-in glyph into single-channel `R8` coverage `[0..=255]`.
pub fn rasterize_bitmap_glyph(cp: u32, size_px: i32) -> (i32, i32, Vec<u8>) {
    let bits = glyph_8x16(cp);
    let (w, h) = bitmap_scaled_dims(size_px);
    let mut out = vec![0u8; (w as usize) * (h as usize)];
    for py in 0..h {
        let sy = ((py * BITMAP_CELL_H) / h).clamp(0, BITMAP_CELL_H - 1) as usize;
        let row_byte = bits[sy];
        for px in 0..w {
            let sx = ((px * BITMAP_CELL_W) / w).clamp(0, BITMAP_CELL_W - 1) as u32;
            let on = (row_byte & (0x80u8 >> sx)) != 0;
            out[(py as usize) * (w as usize) + (px as usize)] = if on { 255 } else { 0 };
        }
    }
    (w, h, out)
}
